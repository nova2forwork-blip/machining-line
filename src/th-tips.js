const norm = (s) => String(s || "").replace(/[⠿↕▲▼↺▾▴]/g, "").replace(/\s+/g, " ").trim();
const KEYED = new Map(Object.entries(TIPS).map(([k, v]) => [k.toUpperCase(), v]));
const GENERIC = /^(กดเพื่อเรียง|ลากที่จับ|Click to sort|Drag ⠿)/;
// ตารางที่ไม่ทำ: หน้าเครื่อง (คลาส stn-…) · ใบพิมพ์
const SKIP = '[class^="stn"], [class*=" stn-"], .lot-sheet, .print-only, [data-no-thtips]';

function apply(root) {
  const ths = (root || document).querySelectorAll("thead th:not([title]):not([data-thtip])");
  for (const th of ths) {
    if (th.closest(SKIP)) continue;
    const t = norm(th.textContent); if (!t || t.length > 40) continue;
    const tip = KEYED.get(t.toUpperCase());
    if (tip) { th.setAttribute("title", tip); th.setAttribute("data-thtip", "1"); }
  }
  // ตารางที่ลากสลับคอลัมน์ได้ (DataTable): หัวมี title ทั่วไปอยู่แล้ว ("กดเพื่อเรียง · ลากที่จับ ⠿ …") → เอาคำอธิบายขึ้นก่อน แล้วตามด้วยข้อความเดิม
  for (const th of (root || document).querySelectorAll("thead th[data-colkey]")) {
    if (th.closest(SKIP)) continue;
    const cur = th.getAttribute("title") || ""; if (!GENERIC.test(cur)) continue;   // มี title เฉพาะของคอลัมน์ / ใส่คำอธิบายไปแล้ว
    const t = norm(th.textContent); if (!t || t.length > 40) continue;
    const tip = KEYED.get(t.toUpperCase());
    if (tip) th.setAttribute("title", `${tip} · ${cur}`);
  }
}

let started = false;
export function installThTips() {
  if (started || typeof document === "undefined" || typeof MutationObserver === "undefined") return; started = true;
  let timer = null;
  const run = () => { timer = null; try { apply(document); } catch { /* ignore */ } };
  const kick = () => { if (!timer) timer = setTimeout(run, 250); };
  new MutationObserver(kick).observe(document.documentElement, { childList: true, subtree: true });
  kick();
  // ช่วยหาหัวที่ยังไม่มีคำอธิบาย (ใช้ตอนตรวจ)
  try { window.__thMissing = () => [...document.querySelectorAll("thead th")].filter((th) => !th.closest(SKIP) && !th.getAttribute("title") && !th.querySelector("[title]") && norm(th.textContent)).map((th) => norm(th.textContent)); } catch { /* ignore */ }
}
